# A função print() exibe uma mensagem ou valores na tela do console. Exemplo:
print("Olá, mundo!")

# A função len() retorna a quantidade de itens de um objeto (como caracteres em uma string). Exemplo:
tamanho = len("Python")

# A função type() retorna o tipo de dado de um valor ou variável. Exemplo:
tipo = type(10)

# A função sum() soma os elementos de uma lista ou sequência numérica. Exemplo:
total = sum([1, 2, 3])

# A função str() converte um valor de qualquer tipo para o formato de texto (string). Exemplo:
texto = str(123)